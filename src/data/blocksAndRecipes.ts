export function patternToIngredients(pattern: (string | null)[]): RecipeIngredient[] {
  const counts = new Map<string, number>();
  for (const id of pattern) {
    if (id) counts.set(id, (counts.get(id) || 0) + 1);
  }
  return Array.from(counts.entries()).map(([id, count]) => ({ id, count }));
}

export function applyActiveMods(mods: ModDefinition[]) {
  const newItems: ItemDef[] = [];
  const newRecipes: RecipeDef[] = [];
  const newOres: ItemDef[] = [];
  const newSurfaceSpawns: ItemDef[] = [];
  const newCommands: ModCommandSpec[] = [];
  const newAchievements: AchievementDef[] = [];
  const seenAchIds = new Set<string>();

  clearCottonLuaRuntime();
  const dependencyPool = [...BUILTIN_COTTON_APIS, ...mods];

  for (const mod of mods) {
    let effBlocks = mod.blocks || [];
    let effItems = mod.items || [];
    let effTools = mod.tools || [];
    let effRecipes = mod.recipes || [];
    let effCommands = mod.commands || [];
    let effAchievements = mod.achievements || [];

    if (mod.isCottonLua && mod.luaSource && !mod.isApi) {
      const compiled = registerCottonLuaModRuntime(mod, dependencyPool);
      if (compiled && compiled.ok) {
        if (compiled.blocks.length > 0) effBlocks = compiled.blocks;
        if (compiled.items.length > 0) effItems = compiled.items;
        if (compiled.tools.length > 0) effTools = compiled.tools;
        if (compiled.recipes.length > 0) effRecipes = compiled.recipes;
        if (compiled.commands.length > 0) effCommands = compiled.commands;
        if (compiled.achievements.length > 0) effAchievements = compiled.achievements;
      }
    }

    for (const blk of effBlocks) {
      const isLiquidBlk = Boolean(blk.isLiquid);
      const hasHooks =
        hasCottonLuaItemHook(blk.id, 'onPlace') ||
        hasCottonLuaItemHook(blk.id, 'onBreak') ||
        hasCottonLuaItemHook(blk.id, 'onUse') ||
        hasCottonLuaItemHook(blk.id, 'onTick');
      const def: ItemDef = {
        id: blk.id,
        name: blk.name,
        category: 'mod',
        isBlock: true,
        pattern: blk.pattern || (isLiquidBlk ? 'water' : 'solid'),
        color: blk.color || '#a855f7',
        secondaryColor: blk.secondaryColor || '#581c87',
        hardness: isLiquidBlk ? -1 : Math.max(0.2, Math.min(15, Number(blk.hardness) || 1.2)),
        blastResistance: Math.max(1, Math.min(100, Number(blk.blastResistance) || 6)),
        preferredTool: isLiquidBlk ? 'none' : blk.preferredTool || 'pickaxe',
        minToolTier: typeof blk.minToolTier === 'number' ? blk.minToolTier : 0,
        transparent: Boolean(blk.transparent) || Boolean(blk.customModel?.parts?.length),
        nonSolid: Boolean(blk.nonSolid),
        liquid: isLiquidBlk,
        hiddenInInventory: isLiquidBlk,
        liquidSpread: isLiquidBlk ? Math.max(1, Math.min(7, blk.liquidSpread ?? 5)) : undefined,
        liquidFlowDelayMs: isLiquidBlk
          ? Math.max(80, Math.min(1500, blk.liquidFlowDelayMs ?? 180))
          : undefined,
        liquidHarmful: isLiquidBlk ? Boolean(blk.liquidHarmful) : undefined,
        lightLevel: blk.glow ? (blk.lightLevel || 14) : 0,
        customTexture: blk.customTexture,
        faceTextures: blk.faceTextures,
        customModel: blk.customModel,
        animation: blk.animation,
        hasLuaHooks: hasHooks,
        minSpawnY: typeof blk.minSpawnY === 'number' ? blk.minSpawnY : 4,
        maxSpawnY: typeof blk.maxSpawnY === 'number' ? blk.maxSpawnY : 48,
        spawnBiomes: blk.spawnBiomes?.length ? blk.spawnBiomes : undefined,
        stackSize: 64,
        modId: mod.id,
      };
      newItems.push(def);
      if (blk.spawnAsOre) {
        newOres.push(def);
      }
      if (blk.spawnOnSurface) {
        newSurfaceSpawns.push(def);
      }
      if (blk.craftPattern && blk.craftPattern.some(Boolean)) {
        const ings = patternToIngredients(blk.craftPattern);
        if (ings.length > 0) {
          newRecipes.push({
            id: `mod_rec_${mod.id}_${blk.id}`,
            name: blk.name,
            ingredients: ings,
            pattern: blk.craftPattern,
            output: { id: blk.id, count: blk.craftOutputCount || 2 },
            modId: mod.id,
          });
        }
      } else if (blk.craftIngredientId && blk.craftIngredientCount > 0) {
        newRecipes.push({
          id: `mod_rec_${mod.id}_${blk.id}`,
          name: blk.name,
          ingredients: [{ id: blk.craftIngredientId, count: blk.craftIngredientCount }],
          output: { id: blk.id, count: blk.craftOutputCount || 2 },
          modId: mod.id,
        });
      }
    }

    for (const item of effItems) {
      const isBucket = item.itemKind === 'bucket' || Boolean(item.placesLiquidId);
      const hasHooks =
        hasCottonLuaItemHook(item.id, 'onUse') ||
        hasCottonLuaItemHook(item.id, 'onPlace') ||
        hasCottonLuaItemHook(item.id, 'onAttack') ||
        hasCottonLuaItemHook(item.id, 'onTick');
      const def: ItemDef = {
        id: item.id,
        name: item.name,
        category: 'mod',
        isBlock: false,
        pattern: isBucket ? 'water' : 'metal_block',
        color: item.color || '#38bdf8',
        secondaryColor: item.liquidSecondaryColor || item.secondaryColor || '#bae6fd',
        hardness: 0,
        preferredTool: 'none',
        placesLiquidId: item.placesLiquidId,
        foodValue: item.itemKind === 'food' ? Math.max(1, item.foodValue || 6) : undefined,
        customTexture: item.customTexture,
        customModel: item.customModel,
        animation: item.animation,
        weapon: item.weapon,
        hasLuaHooks: hasHooks,
        stackSize: isBucket ? 1 : Math.max(1, Math.min(64, item.stackSize || 64)),
        modId: mod.id,
      };
      newItems.push(def);
      if (item.craftPattern && item.craftPattern.some(Boolean)) {
        const ings = patternToIngredients(item.craftPattern);
        if (ings.length > 0) {
          newRecipes.push({
            id: `mod_rec_${mod.id}_${item.id}`,
            name: item.name,
            ingredients: ings,
            pattern: item.craftPattern,
            output: { id: item.id, count: item.craftOutputCount || 1 },
            modId: mod.id,
          });
        }
      }
    }

    for (const tool of effTools) {
      const hasHooks =
        hasCottonLuaItemHook(tool.id, 'onUse') ||
        hasCottonLuaItemHook(tool.id, 'onAttack') ||
        hasCottonLuaItemHook(tool.id, 'onTick');
      const def: ItemDef = {
        id: tool.id,
        name: tool.name,
        category: 'mod',
        isBlock: false,
        pattern: 'metal_block',
        color: tool.color || '#f43f5e',
        hardness: 0,
        preferredTool: 'none',
        toolType: tool.toolType || 'pickaxe',
        toolTier: tool.toolTier || 4,
        miningSpeed: tool.miningSpeed || 9,
        durability: tool.durability || 500,
        customTexture: tool.customTexture,
        customModel: tool.customModel,
        animation: tool.animation,
        weapon: tool.weapon,
        hasLuaHooks: hasHooks,
        stackSize: 1,
        modId: mod.id,
      };
      newItems.push(def);
      if (tool.craftPattern && tool.craftPattern.some(Boolean)) {
        const ings = patternToIngredients(tool.craftPattern);
        if (ings.length > 0) {
          newRecipes.push({
            id: `mod_rec_${mod.id}_${tool.id}`,
            name: tool.name,
            ingredients: ings,
            pattern: tool.craftPattern,
            output: { id: tool.id, count: 1 },
            modId: mod.id,
          });
        }
      } else if (tool.craftIngredientId && tool.craftIngredientCount > 0) {
        newRecipes.push({
          id: `mod_rec_${mod.id}_${tool.id}`,
          name: tool.name,
          ingredients: [
            { id: tool.craftIngredientId, count: tool.craftIngredientCount },
            { id: 'stick', count: 2 },
          ],
          output: { id: tool.id, count: 1 },
          modId: mod.id,
        });
      }
    }

    for (const rec of effRecipes) {
      let ingredients: RecipeIngredient[] = [];
      if (rec.pattern && rec.pattern.some(Boolean)) {
        ingredients = patternToIngredients(rec.pattern);
      } else if (rec.ingredients && rec.ingredients.length > 0) {
        ingredients = rec.ingredients;
      } else if (rec.ingredientA) {
        ingredients = [{ id: rec.ingredientA, count: rec.countA || 1 }];
        if (rec.ingredientB && rec.countB && rec.countB > 0) {
          ingredients.push({ id: rec.ingredientB, count: rec.countB });
        }
      }
      if (ingredients.length === 0) continue;
      newRecipes.push({
        id: rec.id,
        name: rec.name,
        ingredients,
        ...(rec.pattern && rec.pattern.some(Boolean) ? { pattern: rec.pattern } : {}),
        output: { id: rec.outputId, count: rec.outputCount || 1 },
        requiresFurnace: Boolean(rec.requiresFurnace),
        modId: mod.id,
      });
    }

    for (const cmd of effCommands) {
      const clean = (cmd.command || '').trim().replace(/^\/+/, '').toLowerCase();
      if (clean) {
        newCommands.push({ ...cmd, command: clean });
      }
    }

    for (const ach of effAchievements) {
      if (!ach?.id || seenAchIds.has(ach.id)) continue;
      seenAchIds.add(ach.id);
      newAchievements.push({ ...ach, modId: ach.modId || mod.id });
    }
  }

  activeModItems = newItems;
  activeModRecipes = newRecipes;
  activeModOreBlocks = newOres;
  activeModSurfaceSpawns = newSurfaceSpawns;
  activeModCommands = newCommands;
  activeModAchievements = newAchievements;
  modItemMap.clear();
  for (const item of newItems) {
    modItemMap.set(item.id, item);
  }
  registryVersion++;
}

const vanillaItemMap = new Map<string, ItemDef>();
for (const item of VANILLA_ITEMS) {
  vanillaItemMap.set(item.id, item);
}
const modItemMap = new Map<string, ItemDef>();

export function getRegistryVersion(): number {
  return registryVersion;
}

export function getAllItems(): ItemDef[] {
  return [...VANILLA_ITEMS, ...activeModItems];
}

export function getPlaceableBlocks(): ItemDef[] {
  return getAllItems().filter(
    (item) => item.isBlock && item.id !== 'bedrock' && !item.hiddenInInventory && !item.liquid,
  );
}

export function getBucketForLiquid(liquidId: string): ItemDef | undefined {
  return getAllItems().find((item) => item.placesLiquidId === liquidId);
}

export function getAllRecipes(): RecipeDef[] {
  return [...VANILLA_RECIPES, ...activeModRecipes];
}

export function getModOreSpawns(): ItemDef[] {
  return activeModOreBlocks;
}

export function getModSurfaceSpawns(): ItemDef[] {
  return activeModSurfaceSpawns;
}

export function getActiveModCommands(): ModCommandSpec[] {
  return activeModCommands;
}

export function getActiveModAchievements(): AchievementDef[] {
  return activeModAchievements;
}

export function getAllAchievements(): AchievementDef[] {
  return [...ACHIEVEMENTS, ...activeModAchievements];
}

export function getItemDef(id: string): ItemDef | undefined {
  return modItemMap.get(id) ?? vanillaItemMap.get(id);
}
